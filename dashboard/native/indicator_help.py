"""Detailed, structured explanations for the implemented non-regression metrics."""


def explain_metric(row, category='basis', price_input='basis'):
    code=row['id'];family=code.split('.')[0]
    pair=category!='basis'
    x={'future':'真实期货价格 F','basis':'调整基差 B = 10000 × (F − S + D) / S，单位 bp',
       'annual':'调整年化 Y = B × 365 / (100T)，单位年化百分点'}[price_input]
    if pair and family in ('A03','A11','B01','B02','B10'):x+='；本项 x = A腿序列 − B腿序列'
    elif pair:x+='；各腿独立计算后再作差'
    variables=[('x',x),('t','当前完整观测；t−k 表示此前第 k 个有效交易时点，不跨缺口拼接')]
    window='按图中标明的历史频率；显示范围只控制图形，不改变计算窗口。'
    reading=[row['meaning']]
    boundaries=['缺中间交易日或相应频率数据时留空；最后有效历史值保留原日期。']
    formula=row['formula']
    if family=='A02':
        variables=[('B','分红调整基差，单位 bp'),('T','实际到期日减观察日，自然日数')]
        formula='假设每日收敛量级 = −B / T'
        window='当前单点；T > 0。'
        reading=['贴水时为正，表示假设到期基差线性归零所对应的每日量级。','它不是期货实际日收益，也不是可锁定收益。']
        boundaries=['T ≤ 0、分红缺失或期现不同步时不提供当前值。']
    elif family=='A03':
        if code.endswith('.z'):
            formula='μ = Σ(x[t−20] … x[t−1]) / 20\ns = √[Σ(xᵢ − μ)² / 19]\nZₜ = (xₜ − μ) / s'
            variables += [('μ / s','前20个值的均值 / 样本标准差；不含当前值')]
            reading=['正值：高于自身历史均值；负值：低于均值。','绝对值表示偏离了多少个历史标准差，不表示未来必然回归。']
            boundaries=['需当前值和此前20个连续值；零方差、缺数时不计算。']
        elif code.endswith('.percentile'):
            formula='分位% = 100 × [N(xᵢ < xₜ) + 0.5N(xᵢ = xₜ)] / 20'
            variables += [('N','前20个观测中满足条件的个数；并列值计半权')]
            reading=['例如80%：当前值在此前20个值中的位置较高。','分位衡量历史位置，不等于盈利概率。']
            boundaries=['历史窗口排除当前值，必须有完整的前20个值。']
        else:
            formula='五期变化 = xₜ − xₜ₋₅';reading=['保留输入本身的单位；基差和年化使用差值。','负基差及过零均可计算，不除以前一期基差。']
            boundaries=['需连续6个观测；中间缺数时留空。']
        window='Z / 分位：此前20个完整日线值；变化：5期。固定具体合约或固定合约对。'
    elif family in ('A04','A05','A06'):
        variables=[('F / D','真实期货价 / 对应合约剩余分红情景点数'),('S','对应现货指数点位'),('T','实际到期自然日；近、远腿使用各自到期日')]
        window='当前同刻观测或同日完整收盘；跨品种必须同月且同到期日。'
        if family=='A04':reading=['方向为近月减远月；正值表示调整后近月更高。','标准化口径除以同品种现货指数，单位 bp。']
        elif family=='A05':
            variables += [('ΔT','远月到期日 − 近月到期日，自然日')]
            reading=['将调整后远近月价格比按到期日间隔做简单年化。','不是两腿各自年化基差相减，也不是可成交盘口价差。']
            boundaries=['ΔT 必须大于0；调整后近月价格必须为正，两腿分红均须有效。']
        else:reading=['先计算各自调整基差 bp，再作 A−B；不会直接相减两个指数点位。','正值表示A的调整基差相对更高。']
    elif family=='A07':
        variables=[('F_A / F_B','两腿实际期货价格，必须为正'),('S_A / S_B','两腿对应指数价格'),('D_A / D_B','各自分红情景，单独归因'),('Δ₅','与5个交易日前的差，需连续6个观测')]
        window='固定合约对的5日对数收益分解，乘10000后单位为 bp。'
        reading=['实际期货收益差 = 指数收益差贡献 + 未调整对数基差贡献。','分红情景变换单列，不能把 F+D 的变动当作期货实际收益。']
        boundaries=['只对正的真实价格或有效正比值取对数；禁止对有符号基差取对数。']
    elif family=='A09':
        variables=[('F_A / F_B','两腿真实期货价格'),('M_A / M_B','合约乘数：IF/IH为300，IC/IM为200'),('h','每1手A对应的理论B手数')]
        window='当前有效报价或完整历史收盘价。'
        reading=['以每手名义金额匹配：h = F_A M_A / (F_B M_B)。','整数匹配展示round(h)后的金额差；名义金额不是保证金。']
        boundaries=['只用真实价格；小数手只是理论比例，取整为0时小规模无法匹配。']
    elif family=='A11':
        formula='波动量级 = √[Σ 最近30个连续分钟的 (Δx)²]'
        variables=[('Δx','真实单腿期货：10000 × ln(Fₜ/Fₜ₋₁)；有符号基差或价差：xₜ−xₜ₋₁'),('单位','与对应变化单位一致；不是再乘年度系数的年化波动率')]
        window='最近30个连续分钟变化；需要31个连续观测。'
        reading=['表示短窗内累计变动幅度；越大代表该窗路径波动越大。','不同输入或单位的数值不可直接比较。']
        boundaries=['午休、跨日、缺分钟会重置；HTTP轮询样本不作为完整分钟线。']
    elif family=='A12':
        formula='Zₜ = (xₜ − μ前30分钟) / s前30分钟\n连续3根同方向 |Z| ≥ 2 → 本次偏离事件计1次'
        variables=[('x','固定使用调整基差 bp；跨期使用近远月调整基差之差'),('事件','首次满足连续3根计1次；持续第4根不会重复计数')]
        window='前30分钟参考 + 连续3根确认；显示当前会话累计事件数。'
        reading=['用于确认偏离持续存在，不是交易触发或未来回归保证。']
        boundaries=['跨会话、缺分钟重置；零方差不产生有效Z；不使用回归残差。']
    elif family=='A13':
        formula='当前未计算成本带；需先定义可执行现货腿、融资与借券条款、双向交易成本。'
        variables=[('额外输入','融资、借券、双向交易成本和可执行现货腿'),('本版状态','输入不足，未输出数值成本带')]
        window='必须按同一到期日、同一时间和方向定义成本。'
        reading=['成本带判断需要可执行输入；示意关系不代表已经实现完整定价模型。']
        boundaries=['缺输入直接不可用；不硬编码成本或利率。']
    elif family=='A14':
        if code.endswith('.etf'):
            variables=[('ETF / IOPV','同一时刻ETF价格和基金参考净值')]
            reading=['正值为溢价，负值为折价；当前没有这两项同步输入。']
        else:
            formula='买近卖远：Ask近 − Bid远\n卖近买远：Bid近 − Ask远'
            variables=[('Bid / Ask','真实期货买一 / 卖一；同时校验对应挂单量'),('方向','始终以近减远表示；不是分红调整后的理论价差')]
            reading=['两个方向对应不同的一档盘口组合。','这是观测报价，不保证两腿能同时成交。']
        window='有效实时同步观测；源时间和接收时间两腿偏差均不超过3秒。'
        boundaries=['陈旧、异常哨兵、倒挂盘口或无有效量时留空。']
    elif family=='B01':
        variables += [('O / C','开盘 / 收盘的对应序列值'),('g','开盘偏离 = Oₜ − xₜ₋₁')]
        window='完整日线；基差或双腿开盘使用09:31首个同步分钟收盘采样。'
        reading=['修复比为正表示日内运动抵消了开盘偏离；等于1对应完全修复。','小于0表示偏离扩大；大于1表示越过前收。']
        boundaries=['修复分母阈值：基差2bp，年化0.02百分点，真实价格为前收的2bp。','只有两腿日线高低价时，不生成基差OHLC。']
    elif family=='B02':
        variables += [('w','实际A合约成交量权重；不创造“基差成交量”'),('中枢偏离','当前对应序列值减中枢')]
        if 'collection' in code:
            formula='采集区间中枢 = Σ(xⱼ × 有效增量V_A,ⱼ) / Σ有效增量V_A,ⱼ' if code.endswith('center') else '采集区间中枢偏离 = 最新x − 采集区间中枢'
            window='同一连续采集区间；时间起点见数据状态。'
            boundaries=['首次、重连、累计量回退及跨会话重建基准；累计量不逐轮相加。','零权重时留空，不称开盘以来VWAP。']
        else:
            window='完整240分钟的同步收盘采样；按该日实际合约分钟成交量加权。'
            boundaries=['分钟缺数、零权重时留空；不是逐笔VWAP。']
        reading=['中枢刻画成交集中出现的序列水平。','有符号基差也可加权；偏离仍用点、bp或年化百分点。']
    elif family=='B03':
        formula='wₜ = max(OIₜ − OIₜ₋₁, 0)\n漂移 = Σ最近5期(Δxₜ × wₜ) / Σ最近5期 wₜ\n双腿：漂移_A − 漂移_B'
        variables += [('OI','真实合约期末持仓存量'),('w','正净增仓作为权重；不是逐笔开仓量')]
        window='5个连续日变化，至少6个有效日值。'
        reading=['衡量净增仓更多的日期，序列倾向向哪边变化。','是可解释代理，无法识别多空账户的实际开仓行为。']
        boundaries=['对应日OI无效、到期归零、|ΔOI|>V或权重全为0时不更新。']
    elif family=='B04':
        variables=[('Vₜ','实际合约完整当日成交量'),('OIₜ','当日有效期末持仓存量'),('ΔOIₜ','OIₜ − OIₜ₋₁；不是把分钟OI相加')]
        window='完整日线；换手用前一交易日的有效OI。'
        reading=['换手率 Q=V/OI前值，表示成交相对前期存量的规模。','净持仓变化比 K=100ΔOI/V，区分净存量变化和流量。']
        boundaries=['OI缺失、前值为0、成交量为0、到期归零或异常ΔOI时不生成虚假减仓。']
    elif family=='B05':
        variables=[('ΔOI近 / ΔOI远','两月当日有效净持仓变化'),('M','近月减少量与远月增加量中较小者'),('前期合计OI','OI近前值 + OI远前值')]
        window='同品种固定近远月对，完整日线。'
        reading=['M衡量“近减远增”的共同规模；R把M除以前期合计OI。','N展示两月合计净增率；这些只描述形态，不能证明同一账户实际移仓。']
        boundaries=['任一腿对应日OI缺失则不更新；禁止把实时OI原值0当作撤仓。']
    elif family=='B06':
        variables=[('V近 / V远','当日两腿全日成交量'),('OI近前 / OI远前','前一交易日有效持仓存量')]
        window='固定近远月对，完整日线；结果单位为百分点。'
        reading=['正值：远月在当日成交中的份额，高于其此前持仓份额。','反映流量相对存量的倾斜，不等于真实资金流入。']
        boundaries=['成交合计、持仓合计须为正；前期任一OI缺失不更新。']
    elif family=='B07':
        variables=[('CLV','(2C−H−L)/(H−L)，范围−1至1'),('差值','(CLV_A−CLV_B)/2，范围−1至1'),('量能条件','两腿各自RVOL≥1时为1，否则0；缺任一RVOL则缺失')]
        window='完整日线；有符号基差OHLC从同步分钟收盘观测聚合。'
        reading=['正值：A收盘在自身当日区间内的位置相对更高。','量能条件单列，不将位置高低直接当作资金方向。']
        boundaries=['H=L时不计算；不同腿日线高低价不能相减构造基差高低价。','期现单对的位置差固定使用真实期货和指数各自OHLC。']
    elif family=='B08':
        variables=[('OI_A合计 / OI_B合计','同一天，对两品种共同且固定月份集合的OI求和'),('Δ₅ lnOI','合计OI相对5个交易日前的对数增长')]
        window='固定月份集合的连续6个完整日值，结果为对数增长百分点。'
        reading=['正值：A同组月份合计持仓扩张更快。','只在同一时点跨月份合计；不会把跨日OI求和，也不拼接换月。']
        boundaries=['集合中任一合约缺OI、到期、合计为0或中间缺日时不更新。']
    elif family=='B09':
        variables=[('RVOL','Vₜ / median(V[t−20:t−1])'),('双腿比较','ln(RVOL_A/RVOL_B)；不是两个品种成交手数直接相减')]
        window='此前20个全日成交量作参考，排除当前日。'
        reading=['单腿RVOL>1表示高于自身近期成交中位数。','双腿对数比为正表示A相对自身基准更活跃。']
        boundaries=['盘中累计量不与历史全日量混算；零中位数、缺数留空。']
    elif family=='B10':
        formula='路径效率 = (xₜ − xₜ₋₅) / Σ最近5期 |xᵢ − xᵢ₋₁|'
        window='连续6个日观测，包含5个变化。'
        reading=['范围−1至1；符号表示方向，绝对值越接近1，路径越单向。','接近0表示往返抵消较多；允许负基差和过零。']
        boundaries=['分母为0或中间缺数时不计算，不除以前一期基差。']
    elif family=='B11':
        variables=[('TR','真实价：max(H−L, |H−前收|, |L−前收|)'),('自身压力','真实价TR/前收或有符号序列绝对振幅，再除以前20期振幅中位数'),('双腿结果','ln(压力A/压力B)；另列max(压力A,压力B)')]
        window='当前完整振幅与此前20期比较，排除当前。'
        reading=['相对值为正表示A振幅压力更大；最大压力用于识别两腿共同高波动。','相对差为0不等于两腿都平静。']
        boundaries=['有符号输入不除以前一期基差；同步分钟不完整或分母为0时留空。']
    elif family=='B12':
        variables=[('h','跨期为1；跨品种为F_A M_A/(F_B M_B)'),('容量A / 容量B','min(V_A,V_B/h) / 容量A×h'),('平衡度','两腿名义成交规模的较小值 / 较大值')]
        window='历史全日量与盘中截至当前累计量分开标记。'
        reading=['展示100%已发生成交量折算的容量基数；参与比例p时再乘p。','名义规模使用真实期货价和乘数；不是可成交承诺，也不依赖β。']
        boundaries=['两腿必须有有效价格、成交量和时间；不使用F+D或基差折算手数。']
    else:
        raise ValueError('缺少该指标的解释：'+code)
    return dict(title=row['title'],formula=formula,variables=variables,window=window,
                reading=reading,boundaries=boundaries,unit=row['unit'],scope=row['scope'])
